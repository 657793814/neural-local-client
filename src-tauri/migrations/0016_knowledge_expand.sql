-- 每个学科建一本「通用考点」教材（已存在就复用）
insert into textbook (id, subject_id, name, grade, sort)
select lower(hex(randomblob(16))), s.id, '通用考点', null, 800
from subject s
where not exists (
    select 1 from textbook t where t.subject_id = s.id and t.name = '通用考点'
);

-- 章节
insert into chapter (id, textbook_id, parent_id, name, sort)
select lower(hex(randomblob(16))), t.id, null, v.chapter, 800
from (select distinct subject, chapter from _nb_point) v
join subject s on s.name = v.subject
join textbook t on t.subject_id = s.id and t.name = '通用考点'
where not exists (
    select 1 from chapter c where c.textbook_id = t.id and c.name = v.chapter
);

-- 知识点：同科同名已存在就跳过（内置目录里已有的不再造一份）
insert into knowledge_point (id, subject_id, chapter_id, name, sort, origin)
select lower(hex(randomblob(16))), t.subject_id, c.id, v.name, 800, 'builtin'
from _nb_point v
join subject s on s.name = v.subject
join textbook t on t.subject_id = s.id and t.name = '通用考点'
join chapter c on c.textbook_id = t.id and c.name = v.chapter
where not exists (
    select 1 from knowledge_point k
    where k.subject_id = t.subject_id and trim(k.name) = v.name
);

drop table _nb_point;
